HERE = os.path.dirname(os.path.abspath(__file__))
EPS = 1e-9


def affine(p, w):
    # a(x) = 2 p.x - h with h = |p|^2 - w
    h = p[0] ** 2 + p[1] ** 2 - w
    return (2 * p[0], 2 * p[1], -h)


def ev(a, x):
    return a[0] * x[0] + a[1] * x[1] + a[2]


def clip(poly, f):
    # keep {x : f(x) >= 0}
    out = []
    for k in range(len(poly)):
        P, Q = poly[k], poly[(k + 1) % len(poly)]
        fp, fq = f(P), f(Q)
        if fp >= -EPS:
            out.append(P)
        if (fp > EPS and fq < -EPS) or (fp < -EPS and fq > EPS):
            t = fp / (fp - fq)
            out.append((P[0] + t * (Q[0] - P[0]), P[1] + t * (Q[1] - P[1])))
    return out


def diagram(sites, weights, box):
    A = [affine(p, w) for p, w in zip(sites, weights)]
    x0, y0, x1, y1 = box
    cells = []
    for i in range(len(sites)):
        poly = [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]
        for j in range(len(sites)):
            if j != i:
                ai, aj = A[i], A[j]
                poly = clip(poly, lambda x, ai=ai, aj=aj: ev(ai, x) - ev(aj, x))
        cells.append(poly)
    facets = {}
    for i in range(len(sites)):
        for j in range(i + 1, len(sites)):
            pts = [x for x in cells[i] if abs(ev(A[i], x) - ev(A[j], x)) < 1e-7]
            if len(pts) >= 2:
                facets[(i, j)] = (pts[0], pts[-1])
    return A, cells, facets


def fmt(x):
    return "(%.3f,%.3f)" % x


def poly_path(poly):
    return " -- ".join(fmt(x) for x in poly) + " -- cycle"


