# ---------------------------------------------------------------- lifting (background.tex)
LSITES = [(1.39, 1.16), (0.44, 1.38), (1.63, 0.27), (1.35, 0.68), (0.79, 0.36)]
LWEIGHTS = [0.05, 0.14, 0.01, 0.003, 0.05]
LBOX = (0.0, 0.0, 2.0, 2.0)
LA, LCELLS, LFACETS = diagram(LSITES, LWEIGHTS, LBOX)
assert all(len(c) >= 3 for c in LCELLS)
# subtract the common affine function 2 m.x (a homothety, same cells) to flatten the envelope
m = (sum(p[0] for p in LSITES) / len(LSITES), sum(p[1] for p in LSITES) / len(LSITES))
LA = [(a[0] - 2 * m[0], a[1] - 2 * m[1], a[2]) for a in LA]
LZMIN = min(ev(LA[i], x) for i, poly in enumerate(LCELLS) for x in poly)
ZS, ZOFF = 0.28, 1.3
LCOLORS = ["nsBlue", "nsOrange", "nsGreen", "nsPurple", "nsRed"]


def lift(x, a):
    return "(%.3f,%.3f,%.3f)" % (x[0], x[1], ZOFF + ZS * (ev(a, x) - LZMIN))


def flat(x):
    return "(%.3f,%.3f,0)" % (x[0], x[1])


body = ""
for i, poly in enumerate(LCELLS):
    body += "  \\fill[%s!18] %s -- cycle;\n" % (LCOLORS[i], " -- ".join(flat(x) for x in poly))
for (i, j), (P, Q) in LFACETS.items():
    body += "  \\draw[nsFacet] %s -- %s;\n" % (flat(P), flat(Q))
body += "  \\draw[nsDomain] %s -- cycle;\n" % " -- ".join(flat(x) for x in [(0, 0), (2, 0), (2, 2), (0, 2)])
# sites drawn as power circles of radius sqrt(w_i), with a dot at the center
for i, (p, w) in enumerate(zip(LSITES, LWEIGHTS)):
    r = math.sqrt(w)
    if r > 0:
        ring = [(p[0] + r * math.cos(2 * math.pi * k / 48), p[1] + r * math.sin(2 * math.pi * k / 48)) for k in range(48)]
        body += "  \\filldraw[%s!45, draw=%s, line width=0.4pt] %s -- cycle;\n" % (
            LCOLORS[i], LCOLORS[i], " -- ".join(flat(x) for x in ring))
    body += "  \\node[circle, fill=black, inner sep=0.7pt] at %s {};\n" % flat(p)
# vertical guides from the diagram vertices
verts = []
for (i, j), (P, Q) in LFACETS.items():
    for X in (P, Q):
        if all(abs(X[0] - V[0]) + abs(X[1] - V[1]) > 1e-6 for V, _ in verts):
            verts.append((X, i))
for X, i in verts:
    body += "  \\draw[nsGuide] %s -- %s;\n" % (flat(X), lift(X, LA[i]))
# lifted planes, back to front
for i, poly in sorted(enumerate(LCELLS), key=lambda c: -sum(x[1] for x in c[1]) / len(c[1])):
    body += "  \\filldraw[%s!55, draw=black, line width=0.4pt, fill opacity=0.9] %s -- cycle;\n" % (
        LCOLORS[i], " -- ".join(lift(x, LA[i]) for x in poly))
for (i, j), (P, Q) in LFACETS.items():
    body += "  \\draw[nsRidge] %s -- %s;\n" % (lift(P, LA[i]), lift(Q, LA[i]))
with open(os.path.join(HERE, "lifting.tex"), "w") as f:
    f.write(HEADER + "\\begin{tikzpicture}[x={(1.1cm,-0.15cm)}, y={(0.45cm,0.5cm)}, z={(0cm,0.75cm)}]\n"
            + body + "\\end{tikzpicture}\n")
